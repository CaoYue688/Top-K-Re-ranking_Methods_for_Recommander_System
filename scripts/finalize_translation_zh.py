    target_blocks = blocks(TARGET.read_text(encoding="utf-8"))
    if len(source_blocks) != 498 or len(target_blocks) != len(source_blocks):
        raise ValueError(
            f"Unexpected alignment: source={len(source_blocks)}, target={len(target_blocks)}"
        )
    for block_number, translation in REVIEWED_BLOCKS.items():
        if not source_blocks[block_number - 1].strip():
            raise ValueError(f"Source block {block_number} is unexpectedly empty")
        target_blocks[block_number - 1] = translation
    result = "\n\n".join(target_blocks) + "\n"
    for source, target in REPLACEMENTS:
        result = result.replace(source, target)
    TARGET.write_text(result, encoding="utf-8")
    print(f"reviewed_blocks={len(REVIEWED_BLOCKS)}")
    print(f"output={TARGET}")


